"""Generate the blinded manuscript (manuscript/main_acs_blind.tex) from manuscript/main_acs.tex:
author block replaced, internal notes for coauthors removed, repository link withheld, and the
acknowledgements section dropped (the disclosure statement is kept).  Usage: python3 make_blind.py"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(HERE, "..", "manuscript", "main_acs.tex")
dst = os.path.join(HERE, "..", "manuscript", "main_acs_blind.tex")
t = open(src).read()

start = t.index("Chong Wang$^{1}$")
end = t.index("\\end{center}", start)
t = t[:start] + "Authors blinded for review\n" + t[end:]

t = re.sub(r"\\newcommand\{\\coauthorq\}\[1\]\{.*\}\n", r"\\newcommand{\\coauthorq}[1]{}\n", t)
t = re.sub(r"\\newcommand\{\\authornote\}\[1\]\{.*\}\n", r"\\newcommand{\\authornote}[1]{}\n", t)
t = re.sub(r"\n\\coauthorq\{[^\n]*\}\n", "\n", t)            # drop the notes to coauthors from the source too
t = t.replace("; also at \\url{https://github.com/chongwangstat/rare-event-nma-contributions}.", "; repository link withheld for review.")
a = t.index("\\section*{Acknowledgements}")
b = t.index("\\section*{Disclosure Statement}")
t = t[:a] + t[b:]
t = t.replace("%% The blinded version is generated from this file by code/make_blind.py; do not edit main_acs_blind.tex.",
              "%% GENERATED by code/make_blind.py from main_acs.tex -- do not edit.")
for name in ["Chong", "Iowa State", "chongwangstat", "Gongbo", "Weng", "Zhezhen", "Mailman", "Irving", "iastate"]:
    assert name not in t, name
open(dst, "w").write(t)
print("wrote", os.path.abspath(dst))
